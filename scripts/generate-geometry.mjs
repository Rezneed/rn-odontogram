import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

import getBounds from 'svg-path-bounds';

const here = dirname(fileURLToPath(import.meta.url));
const pathsFile = resolve(here, '../src/data/teeth.paths.ts');
const outFile = resolve(here, '../src/data/teeth.geometry.ts');

const source = readFileSync(pathsFile, 'utf8');
const literal = source.slice(
  source.indexOf('= [') + 2,
  source.lastIndexOf(']') + 1,
);
const teeth = new Function(`return ${literal}`)();

const round = value => Math.round(value * 1000) / 1000;

const boundsOf = tooth => {
  const paths = [
    tooth.outlinePath,
    tooth.shadowPath,
    ...(Array.isArray(tooth.lineHighlightPath)
      ? tooth.lineHighlightPath
      : [tooth.lineHighlightPath]),
  ];

  return paths
    .map(getBounds)
    .reduce((acc, [left, top, right, bottom]) => [
      Math.min(acc[0], left),
      Math.min(acc[1], top),
      Math.max(acc[2], right),
      Math.max(acc[3], bottom),
    ]);
};

const entries = teeth.map(tooth => {
  const bounds = boundsOf(tooth).map(round);
  return `  {name: '${tooth.name}', bounds: [${bounds.join(', ')}]},`;
});

const output = [
  '// GENERATED by scripts/generate-geometry.mjs — do not edit by hand.',
  '// Bounding box of every path of a tooth, in upper-right-quadrant',
  '// coordinates. Lets the chart crop its viewBox and place tooth labels',
  '// without a rendered-DOM measurement pass (there is none in React Native).',
  '',
  "import {IToothBounds} from '../odontogram.types';",
  '',
  'export const TOOTH_BOUNDS: readonly IToothBounds[] = [',
  ...entries,
  '];',
  '',
].join('\n');

writeFileSync(outFile, output);
process.stdout.write(`wrote ${entries.length} tooth bounds to ${outFile}\n`);
